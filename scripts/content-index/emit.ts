const stillKeys = { stillImagePath: 'stillUrl' } as const;
const pathKeys = { imagePath: 'imageUrl' } as const;

/**
 * The bundled cutaways module: summaries, plus the still imports the per-record JSON refers to by
 * repo path (`cutawayStillUrls`), so stills stay hashed bundler assets.
 */
export function emitCutawaysModule(
  summaries: readonly CutawaySummaryRecord[],
  stillPaths: readonly string[],
): string {
  const unique = [...new Set(stillPaths)].sort();
  const imports = unique.map((path, index) => `import cutawayImg${index} from '../../../${path}';`);
  const map = unique.map((path, index) => `  ${toTsString(path)}: cutawayImg${index},`).join('\n');
  return `// AUTO-GENERATED by scripts/content-index — do not edit
${imports.length > 0 ? `${imports.join('\n')}\n\n` : ''}import type { CutawaySummary } from '../types';

/** Repo still path (a segment's \`stillImagePath\` in the per-record JSON) → bundled URL. */
export const cutawayStillUrls: Readonly<Record<string, string>> = {
${map}
};

export const cutawaySuggestions: CutawaySummary[] = ${formatLiteral(summaries, 0)};
`;
}

export function emitGalleryModule(scenes: FilmSceneRecord[]): string {
  const { literal, importLines } = emitRecords(scenes, {
    importPrefix: 'galleryImg',
    imageKeys: pathKeys,
  });
  return emitModule(importLines, 'FilmScene', 'filmScenes', 'FilmScene', literal);
}

