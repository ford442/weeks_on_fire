export function emitSceneBoardsModule(boards: SceneBoardRecord[]): string {
  // `imagePath` is rewritten wherever it nests (each board's frames); import aliases are keyed by
  // path, so two boards that share a still share one import.
  const { literal, importLines } = emitRecords(boards, {
    importPrefix: 'sceneImg',
    imageKeys: pathKeys,
  });
  return emitModule(importLines, 'SceneBoard', 'sceneBoards', 'SceneBoard', literal);
}

