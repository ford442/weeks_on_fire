export function emitSequencesModule(sequences: SequenceRecord[]): string {
  const { literal, importLines } = emitRecords(
    sequences.map((sequence) => ({
      ...sequence,
      renderer: sequence.graph ? 'graph' : 'custom',
    })),
    { importPrefix: 'sequenceImg', imageKeys: stillKeys, inline: ['graph'] },
  );
  return emitModule(importLines, 'SequenceRecord', 'sequenceRecords', 'SequenceRecord', literal);
}

export interface CatalogRefLists {
  songs: ReadonlyArray<{ id: string; title: string }>;
  cutaways: ReadonlyArray<{ id: string; title: string }>;
  sequences: ReadonlyArray<{ id: string; title: string }>;
  cartoons: ReadonlyArray<{ id: string; title: string }>;
  characters: ReadonlyArray<{ id: string; name: string }>;
}

/**
 * `{ id, title }` pairs and nothing else, so the Timeline can label and link catalog refs without
 * importing the full song lyrics or cutaway segment prompts (hundreds of KB each).
 */
export function emitCatalogRefsModule(lists: CatalogRefLists): string {
  const block = (name: string, items: ReadonlyArray<{ id: string; title: string }>) =>
    `export const ${name}: CatalogRef[] = [\n${items
      .map((item) => `  { id: ${toTsString(item.id)}, title: ${toTsString(item.title)} },`)
      .join('\n')}\n];\n`;

  return `// AUTO-GENERATED by scripts/content-index — do not edit
export interface CatalogRef {
  id: string;
  title: string;
}

${block('songRefs', lists.songs)}
${block('cutawayRefs', lists.cutaways)}
${block('sequenceRefs', lists.sequences)}
${block('cartoonRefs', lists.cartoons)}
${block(
  'characterRefs',
  lists.characters.map((character) => ({ id: character.id, title: character.name })),
)}`;
}

/**
 * The Overview strip: a few dozen slim records picked by `whats-new.ts`. Stills become bundler
 * imports like every other generated module, so the landing page ships thumbnails but no prompts.
 */
export function emitWhatsNewModule(items: readonly WhatsNewItem[]): string {
  const { literal, importLines } = emitRecords(items, {
    importPrefix: 'whatsNewImg',
    imageKeys: pathKeys,
  });
  const imports = importLines ? `${importLines}\n\n` : '';
  return `// AUTO-GENERATED by scripts/content-index — do not edit
${imports}export type WhatsNewKind = 'song' | 'suggestion' | 'cartoon' | 'sequence' | 'video' | 'image';

export interface WhatsNewEntry {
  kind: WhatsNewKind;
  id: string;
  title: string;
  blurb: string;
  /** YYYY-MM-DD */
  added: string;
  imageUrl?: string;
  /** Songs only: an mp3 is linked. */
  audio?: boolean;
}

/** Newest first. */
export const whatsNew: WhatsNewEntry[] = ${literal};
`;
}

/** `{ key: "value", … }` on one line: one record per line keeps big generated lists diffable. */
function inlineObject(record: object): string {
  return `{ ${Object.entries(record)
    .map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
    .join(', ')} }`;
}

const union = (values: readonly string[]) => values.map((value) => toTsString(value)).join(' | ');

/** The catalog graph (`catalog-graph.ts`): slim nodes and typed edges, no catalog bodies. */
export function emitCatalogGraphModule(graph: CatalogGraph): string {
  const lines = (items: readonly object[]) =>
    items.map((item) => `    ${inlineObject(item)},`).join('\n');
  return `// AUTO-GENERATED by scripts/content-index — do not edit
export type CatalogNodeType = ${union(CATALOG_NODE_TYPES)};

export type CatalogRel = ${union(CATALOG_RELS)};

export interface CatalogNode {
  /** \`\${type}:\${id}\` */
  key: string;
  type: CatalogNodeType;
  id: string;
  title: string;
  /** Router path (no basename), including any query string. */
  path: string;
}

export interface CatalogEdge {
  from: string;
  to: string;
  rel: CatalogRel;
}

export interface CatalogGraph {
  nodes: CatalogNode[];
  edges: CatalogEdge[];
}

export const catalogGraph: CatalogGraph = {
  nodes: [
${lines(graph.nodes)}
  ],
  edges: [
${lines(graph.edges)}
  ],
};
`;
}

/** The hub search corpus (`search-docs.ts`). Imported only by the lazily loaded search chunk. */
export function emitSearchIndexModule(documents: readonly SearchDocument[]): string {
  return `// AUTO-GENERATED by scripts/content-index — do not edit
export type SearchDocType = ${union([...CATALOG_NODE_TYPES, 'crew'])};

export interface SearchDocument {
  /** Catalog graph key, \`\${type}:\${id}\`. */
  id: string;
  type: SearchDocType;
  title: string;
  subtitle: string;
  tags: string;
  /** Names of the characters linked by id. */
  characters: string;
  summary: string;
  /** Router path (no basename), including any query string. */
  route: string;
}

export const searchDocuments: SearchDocument[] = [
${documents.map((document) => `  ${inlineObject(document)},`).join('\n')}
];
`;
}
